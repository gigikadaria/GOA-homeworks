# > 
print(10 > 5)   # True
print(3 > 7)    # False

# < 
print(4 < 9)    # True
print(8 < 2)    # False

# <= 
print(5 <= 5)   # True
print(6 <= 3)   # False

# >= 
print(10 >= 10)  # True
print(4 >= 6)    # False

# == 
print(7 == 7)   # True
print(2 == 5)   # False

