# 1) for loop (ციკლი) ვიყენებთ მაშინ, როცა გვინდა რაღაც მოქმედება
# რამდენჯერმე განმეორდეს ავტომატურად.
# ის გადადის რიცხვებზე, სიმბოლოებზე ან ზოგადად სიის ელემენტებზე
# და ყოველი ნაბიჯის დროს ასრულებს ერთსა და იმავე კოდს.

# მარტივი მაგალითი:
for i in range(5):
    print(i)


# 2) Indentation (ინდენტაცია) არის წინ დატოვებული სივრცე (ტაბი ან სფეისი),
# რომელიც გვიჩვენებს, რომ ეს ხაზი ეკუთვნის კონკრეტულ ბლოკს
# (მაგალითად: for-ს, if-ს, ფუნქციას და ა.შ.)
# Python-ში ინდენტაცია აუცილებელია - მის გარეშე კოდი არ იმუშავებს სწორად.

# 3) for ციკლის მეშვეობით რიცხვები 0-დან 67-მდე
for i in range(68):
    print(i)


# 4) for ციკლის მეშვეობით რიცხვები 12-დან 87-მდე
for i in range(12, 88):
    print(i)


# 5) for ციკლის მეშვეობით რიცხვები 4-დან 98-მდე, ყოველი 2 ნაბიჯით
for i in range(4, 99, 2):
    print(i)


# 6) for ციკლის მეშვეობით თქვენი სახელი 10-ჯერ
for i in range(10):
    print("Gigi")   # შეცვალეთ თქვენი სახელით


# 7) მომხმარებლის მიერ შეყვანილი სიტყვის თითოეული ასოს გამოყვანა
word = input("შეიყვანეთ რაიმე სიტყვა: ")

for letter in word:
    print(letter)


# 8) მომხმარებლის მიერ შეყვანილი რიცხვის გამოყენება for ციკლის ბოლო მნიშვნელობად
num = int(input("შეიყვანეთ რიცხვი: "))

for i in range(num):
    print(i)
